CREATE TABLE radio_programme (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kuku_id BIGINT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  slug TEXT NOT NULL,
  description TEXT,
  record_every BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE radio_airing (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kuku_id BIGINT NOT NULL UNIQUE,
  programme_id BIGINT NOT NULL REFERENCES radio_programme (id),
  title TEXT NOT NULL,
  starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
  original_id BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_radio_airing_programme_id ON radio_airing (programme_id);

